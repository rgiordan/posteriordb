"""JAX/TFP translation of posterior_database/models/stan/diamonds.stan
(generated by brms):

    transformed data { center X's non-intercept columns 2..K into Xc, means_X. }
    parameters { vector[Kc] b; real Intercept; real<lower=0> sigma; }
    model {
      target += normal_lpdf(b | 0, 1);
      target += student_t_lpdf(Intercept | 3, 8, 10);
      target += student_t_lpdf(sigma | 3, 0, 10) - 1 * student_t_lccdf(0 | 3, 0, 10);
      if (!prior_only) { target += normal_id_glm_lpdf(Y | Xc, Intercept, b, sigma); }
    }

`student_t_lccdf(0 | 3, 0, 10)` is `log(1 - CDF(0))` for a Student-t
*centered at 0* -- by symmetry that's exactly `log(0.5)` for any df/scale,
a fixed constant (this is brms's standard half-Student-t prior
normalization for a `<lower=0>` parameter, unrelated to `sigma`'s actual
value). `normal_id_glm_lpdf(Y | Xc, Intercept, b, sigma)` is exactly
`normal_lpdf(Y | Intercept + Xc @ b, sigma)` (Stan's fused GLM function is a
compute optimization, not a different distribution).
"""

from __future__ import annotations

import math
from typing import Dict, List

import jax.numpy as jnp
from tensorflow_probability.substrates import jax as tfp

from ..constraints import ConstraintType, ParameterSpec
from ..model import StatisticalModel

tfd = tfp.distributions

_LOG_HALF = -math.log(2.0)  # student_t_lccdf(0 | any df, 0, any scale)


class Diamonds(StatisticalModel):
    def param_specs(self, data) -> List[ParameterSpec]:
        kc = int(data["K"]) - 1
        return [
            ParameterSpec("b", (kc,), ConstraintType.UNCONSTRAINED),
            ParameterSpec("Intercept", (), ConstraintType.UNCONSTRAINED),
            ParameterSpec("sigma", (), ConstraintType.LOWER, bounds=(0.0, None)),
        ]

    def log_density(self, params: Dict[str, jnp.ndarray], data) -> jnp.ndarray:
        b = params["b"]
        intercept = params["Intercept"]
        sigma = params["sigma"]

        x = data["X"]  # (N, K)
        means_x = jnp.mean(x[:, 1:], axis=0)
        xc = x[:, 1:] - means_x[None, :]

        mu = intercept + xc @ b

        f64 = lambda v: jnp.asarray(v, dtype=jnp.float64)  # noqa: E731

        lp = jnp.sum(tfd.Normal(loc=0.0, scale=1.0).log_prob(b))
        lp = lp + tfd.StudentT(df=f64(3.0), loc=f64(8.0), scale=f64(10.0)).log_prob(intercept)
        lp = lp + (
            tfd.StudentT(df=f64(3.0), loc=f64(0.0), scale=f64(10.0)).log_prob(sigma) - _LOG_HALF
        )
        if not bool(data["prior_only"]):
            lp = lp + jnp.sum(tfd.Normal(loc=mu, scale=sigma).log_prob(data["Y"]))
        return lp
